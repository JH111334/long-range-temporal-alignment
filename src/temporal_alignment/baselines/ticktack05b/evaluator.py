"""Task-Aware Strict Evaluator for Protocol P12 and RAW_GREEDY_V1.

Features:
- Task type inferred strictly from question text (schema/prompt), zero reliance on gold target.
- MCQA questions only accept option letters (a, b, c, d).
- Yes/No questions only accept Yes or No.
- Full-vocabulary free generation with token-level logging.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Tuple

import torch


def detect_is_yes_no_task(question_text: str) -> bool:
    """Infer task type strictly from question text without gold target leakage."""
    q_lower = question_text.lower()
    return "yes or no" in q_lower or "answer as yes or no" in q_lower


def build_p12_prompt(question_text: str, tokenizer: Any) -> Tuple[str, bool]:
    """Format prompt per P12 Task-Aware ChatML protocol.

    Args:
        question_text: Raw prompt text.
        tokenizer: HuggingFace tokenizer.

    Returns:
        Tuple of (formatted_chatml_prompt, is_yes_no).
    """
    raw = question_text.strip()
    is_yn = detect_is_yes_no_task(raw)

    if is_yn:
        instruction = "\nAnswer directly with only Yes or No."
    else:
        instruction = "\nAnswer directly with only the option letter (a, b, c, d)."

    messages = [
        {"role": "system", "content": "You are a helpful assistant. Please answer the question by selecting the correct option."},
        {"role": "user", "content": raw + instruction},
    ]

    formatted = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    return formatted, is_yn


def task_conditioned_strict_parser(
    generated_text: str,
    is_yn: bool,
) -> Tuple[Optional[str], str]:
    """Task-conditioned regex parser enforcing strict label compliance.

    Args:
        generated_text: Raw output string generated by model.
        is_yn: Whether the question is a Yes/No task.

    Returns:
        Tuple of (predicted_label_or_None, validity_status).
    """
    cleaned = generated_text.strip()
    if not cleaned:
        return None, "INVALID_EMPTY"

    if is_yn:
        # Check if model mistakenly output an option letter on a Yes/No question
        if re.search(r"\b([a-d])\b", cleaned, re.IGNORECASE) and not re.search(r"\b(Yes|No)\b", cleaned, re.IGNORECASE):
            return None, "INVALID_WRONG_TYPE_LETTER_ON_YN"

        m = re.search(r"\b(Yes|No)\b", cleaned, re.IGNORECASE)
        if m:
            return m.group(1).capitalize(), "VALID"
        return None, "INVALID_SYNTAX_YN"
    else:
        # MCQA question: Check if model mistakenly output Yes/No on MCQA
        if re.search(r"\b(Yes|No)\b", cleaned, re.IGNORECASE) and not re.search(r"\b([a-d])\b", cleaned, re.IGNORECASE):
            return None, "INVALID_WRONG_TYPE_YN_ON_MCQA"

        # Canonical partner regex matching for options
        m = re.search(r"\(([a-d])\)", cleaned, re.IGNORECASE)
        if m:
            return m.group(1).lower(), "VALID"

        m = re.search(r"(?:option|answer|choice|select)\s*[:\-]?\s*\(?([a-d])\)?\b", cleaned, re.IGNORECASE)
        if m:
            return m.group(1).lower(), "VALID"

        m = re.match(r"^([a-d])\b", cleaned, re.IGNORECASE)
        if m:
            return m.group(1).lower(), "VALID"

        m = re.search(r"\b([a-d])\b", cleaned, re.IGNORECASE)
        if m and len(cleaned.split()) <= 5:
            return m.group(1).lower(), "VALID"

        return None, "INVALID_SYNTAX_MCQA"


def evaluate_single_example(
    model: Any,
    tokenizer: Any,
    record: Dict[str, Any],
    max_new_tokens: int = 8,
    temporal_injection_enabled: bool = True,
) -> Dict[str, Any]:
    """Evaluate one example under P12 free-vocabulary generation."""
    raw_input = record.get("input", "") or record.get("text", "")
    gold_target = record.get("target", "").strip()

    # Extract year
    year = record.get("year")
    if year is None:
        cond = record.get("conditioning", {})
        year = cond.get("effective_year", 1947)
    year = int(year)

    formatted_prompt, is_yn = build_p12_prompt(raw_input, tokenizer)
    inputs = tokenizer(formatted_prompt, return_tensors="pt")
    input_ids = inputs["input_ids"].to(next(model.parameters()).device)

    # Free-vocabulary greedy generation
    gen_token_ids = model.generate_free_vocab(
        input_ids=input_ids,
        year=year,
        tokenizer=tokenizer,
        max_new_tokens=max_new_tokens,
        temporal_injection_enabled=temporal_injection_enabled,
    )

    gen_text = tokenizer.decode(gen_token_ids, skip_special_tokens=True).strip()
    parsed_pred, validity_status = task_conditioned_strict_parser(gen_text, is_yn)

    is_valid = (validity_status == "VALID")
    is_correct = False
    if is_valid and parsed_pred is not None:
        if is_yn:
            is_correct = (parsed_pred.lower() == gold_target.lower())
        else:
            is_correct = (parsed_pred.lower() == gold_target.lower())

    return {
        "example_id": record.get("example_id", ""),
        "stage_id": record.get("stage_id", ""),
        "year": year,
        "is_yn": is_yn,
        "gold_target": gold_target,
        "generated_tokens": gen_token_ids,
        "generated_text": gen_text,
        "parsed_pred": parsed_pred,
        "validity_status": validity_status,
        "is_valid": is_valid,
        "is_correct": is_correct,
    }
