            "# --- Kiến trúc Toán học Ticktack (Han et al., 2025) ---\n",
            "def year_to_canchi_polar(years: torch.Tensor, alpha: float = 0.5, beta: float = 0.5) -> Tuple[torch.Tensor, torch.Tensor]:\n",
            "    \"\"\"Chuyển đổi năm sang tọa độ cực (theta, r) theo xoắn ốc Archimedes và chu kỳ Can Chi 60 năm (Eq. 2).\"\"\"\n",
