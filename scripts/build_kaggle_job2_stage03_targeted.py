            "    te = torch.zeros((coord.size(0), hidden_dim), device=device, dtype=torch.float32)\n",
            "    te[:, 0::2] = torch.sin(angles)\n",
            "    te[:, 1::2] = torch.cos(angles)\n",
            "    return te\n",
