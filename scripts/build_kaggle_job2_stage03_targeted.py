            "    te_x = compute_sinusoidal_te(x, hidden_dim)\n",
            "    te_y = compute_sinusoidal_te(y, hidden_dim)\n",
            "    te = (te_x + te_y).unsqueeze(1).to(dtype=dtype)\n",
            "    return te\n",
            "\n",
