            "            s_yes = (max(lg[idx].item() for idx in yes_ids) if yes_ids else -1e9) + prior_bias_rel\n",
            "            s_no = max(lg[idx].item() for idx in no_ids) if no_ids else -1e9\n",
            "            p = 'yes' if s_yes >= s_no else 'no'\n",
