            "        F_core = self.core_gen(self.current_theta, self.current_z)\n",
            "        x_af = torch.bmm(x_a, F_core.transpose(1, 2))\n",
            "        lora_out = F.linear(x_af, self.lora_B.float()) * self.scaling\n",
            "        return base_out + lora_out.to(dtype=x.dtype)\n",
            "\n",
