            "            s_idx = len(all_prompts)\n",
            "            for p in perms:\n",
            "                all_prompts.append(p['prompt'])\n",
            "                all_targets.append(p['target'])\n",
            "                all_years.append(yr)\n",
            "            e_idx = len(all_prompts)\n",
            "            case_perm_slices.append((case, (s_idx, e_idx)))\n",
